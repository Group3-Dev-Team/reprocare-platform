const reviewed = new Map(titles.map((name) => [name.toLowerCase(), name]));

export function facilityDisplayName(facility) {
  const name = facility?.name;
  if (!name) return '';
  const lower = name.toLowerCase();
  if (name !== lower && name !== name.toUpperCase()) return name;
  return reviewed.get(lower) || name;
}
